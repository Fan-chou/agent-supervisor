// 从 packages/daemon/src/schemas.ts 的 JSON Schema 生成 ui/api/types_gen.go（frontend-design §9.2）。
// 用法：bun ui/gen/gen-go.ts [输出文件]（默认 ui/api/types_gen.go）。生成物不手改。
// 约定：可空标量 → 指针；{type:"object"} 无属性 → map[string]any；oneOf（TimelineEntry）由 api/timeline.go 手写。
import { writeFileSync } from "node:fs";
import { schemaFor } from "../../packages/daemon/src/schemas.ts";

type S = Record<string, any>;
const defs = (schemaFor("Timeline") as S).$defs as Record<string, S>;
const out: string[] = [];
const emitted = new Set<string>();
const required: Record<string, string[]> = {};

const goName = (json: string): string =>
  json
    .split("_")
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("")
    .replace(/Id(?=[A-Z]|$)/g, "ID");

function typeOf(s: S): { t: string | null; nullable: boolean } {
  if (Array.isArray(s.type)) {
    const t = s.type.filter((x: string) => x !== "null");
    return { t: t[0] ?? null, nullable: s.type.includes("null") };
  }
  return { t: s.type ?? null, nullable: false };
}

/** 返回 Go 类型；内联对象生成以 ctx 命名的结构体。 */
function goType(s: S, ctx: string): string {
  if (s.$ref) return String(s.$ref).split("/").pop()!;
  if (Object.keys(s).length === 0) return "any";
  const { t, nullable } = typeOf(s);
  const ptr = (x: string) => (nullable ? "*" + x : x);
  switch (t) {
    case "string":
      return ptr("string");
    case "integer":
      return ptr("int64");
    case "number":
      return ptr("float64");
    case "boolean":
      return ptr("bool");
    case "array":
      return "[]" + goType(s.items, ctx + "Item");
    case "object":
      if (s.properties) {
        emitStruct(ctx, s);
        return "*".repeat(0) + ctx; // 内联对象不可空（schema 里没有可空的内联对象）
      }
      if (s.additionalProperties && typeof s.additionalProperties === "object") return "map[string]" + goType(s.additionalProperties, ctx + "Value");
      return "map[string]any";
    default:
      return "any";
  }
}

function emitStruct(name: string, s: S): void {
  if (emitted.has(name)) return;
  emitted.add(name);
  const props = s.properties as Record<string, S>;
  required[name] = (s.required as string[]) ?? [];
  const lines: string[] = [];
  for (const [k, v] of Object.entries(props)) lines.push(`\t${goName(k)} ${goType(v, name + goName(k))} \`json:"${k}"\``);
  out.push(`// ${name} 对应 schema ${name}。\ntype ${name} struct {\n${lines.join("\n")}\n}\n`);
}

for (const [name, s] of Object.entries(defs)) {
  if (name === "TimelineEntry") continue;
  emitStruct(name, s);
}

const reqLines = Object.entries(required)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([n, r]) => `\t"${n}": {${r.map((x) => `"${x}"`).join(", ")}},`);

const src = `// Code generated by ui/gen/gen-go.ts from packages/daemon/src/schemas.ts; DO NOT EDIT.

package api

// SchemaVersion 是生成时的 schema 版本。
const SchemaVersion = "v1"

${out.join("\n")}
// Required 列出每个结构体 schema 里「永远存在」的 JSON 字段（契约测试用）。
var Required = map[string][]string{
${reqLines.join("\n")}
}
`;
writeFileSync(process.argv[2] ?? new URL("../api/types_gen.go", import.meta.url).pathname, src);
console.log(`generated ${emitted.size} structs`);
